# titles.py —— 会话标题：规则占位 + 模型输出的清洗（**纯函数**，不依赖 LLM / DB / 网络）
#
# 为什么需要这一层（实测，444 题 = `测试集/eval_v1.jsonl`）：
#
# ① **标题写到 30 字，但侧边栏只看得见约 15 字。**
#    按现行样式算：侧栏 264px − 内外边距 ≈ 220px 可用，字号 14px → 中文约 15 个字。
#    所以 `question[:30]` 里**后一半用户永远看不到** —— 真正起作用的是前 15 个字。
#
# ② **恰恰是前 15 个字，被不携带信息的开场白占满了。**
#    「请教一下，大学英语四级考试（CET4）考到多少分才能…」→ 可见部分全是寒暄。
#    实测 **17% 的标题前 6 字雷同**（最雷同一组「学科学术委员…」有 10 条），
#    侧边栏扫过去是一片差不多的条目。
#
# ③ **纯规则清洗解决不了区分度** —— 这一条是测出来的、不是猜的：
#    去开场白 + 按标点截断后，平均长度 20.7 → 12.9 字、硬切 161 → 129 条，
#    但**前 6 字雷同反而从 17% 升到 20%**。规则只会"删"，不会"读"：
#    「请教一下，大学英语四级考试」删成「大学英语四级考试」，
#    可「我想申报社会科学研究系列的副研究员」删完仍然和它的兄弟条目撞车。
#    → 规则能把标题**变短变干净**，但**读不出主题**。
#
# ④ 模型能读出主题，但**不守格式**：实测 12 题里约一半无视「最多 12 字」，
#    输出 24~29 字，还漏出训练里学到的答题语气词（「…得分规则**哈～**」）。
#    加示例、收紧 max_tokens 后仍然如此 —— 它是照资料答题的 SFT 模型，
#    "压缩成标题"属于分布外任务。
#
# 所以分工是：**模型负责读出主题，规则负责收尾**（去语气词、去标点、按自然停顿截断）。
# 本模块只做规则那一半，因此保持纯函数 —— 可脱离 LLM 单测，正是把逻辑从
# `routers/chat.py` 与 `llm_client.py` 里搬出来的原因。

import re

# 侧边栏可见约 15 个中文字，留一点余量
TITLE_MAX = 14

# 原问题超过这么长，多半含铺垫（口语化长题）→ 值得叫模型重起
LONG_QUESTION = 24

# ---------------------------------------------------------------- 清洗规则
# 开场寒暄：不携带主题信息，却占着标题最贵的位置。**长词排前面**，否则短词先匹配掉。
_RE_LEAD = re.compile(
    r"^(?:我就是想问问|我就是想问下|我就是想问|想请教一下|麻烦问一下|麻烦问下|麻烦问问|"
    r"我想问一下|我想问下|我想问问|想问一下|想问下|问一下|问下|问个问题|"
    r"想问问(?:学长|学姐|老师|同学)?|"      # 「想问问学长，…」——把人称也一起剥掉
    r"请问一下|请问|请教一下|请教|想请教|我想知道|想知道|我有个问题|有个问题|好奇问一下)"
    r"[，,、：:\s]*"
)
# 口语修饰：「咱们学校的 X」→「X」。限定在「…学校」形态，避免误伤「桂林电子科技大学」。
_RE_SCHOOL = re.compile(r"(?:咱们|咱|我们|贵|本)?学校(?:的)?")
# 句末语气词与标点（模型输出里实测漏出过「哈～」）
_RE_TAIL = re.compile(r"(?:哈|呀|啊|呢|吗|吧|哦|嘛|嗯|啦|咯|哟|嘞|滴|～|~)+$")
_RE_PUNCT = re.compile(r"[？?。.！!，,、；;：:…~～\s]+$")
# 引号/书名号/方括号外壳
_RE_WRAP = re.compile(r'^[\s"\'“”‘’「」『』《》〈〉【】\[\]`]+|[\s"\'“”‘’「」『』`]+$')
# 万一模型把「资料来源」这类训练习惯带出来，从该处截断
_RE_SRCLEAK = re.compile(r"(?:资料来源|参考资料)\s*[:：]?")


def _strip_ends(t: str) -> str:
    """反复去掉尾部的**标点**与**语气词**，直到稳定。

    ⚠️ 顺序有讲究、且必须循环 —— 实测踩过：
      「专升本学制是几年呀？」末尾是 `？`，先跑语气词正则**匹配不上**（`呀` 不在末尾），
      等标点被删掉、`呀` 露出来了，就没人再去删它了。
      写成一前一后两次 sub 的话，线上标题会长成「…是几年呀」这种没洗干净的形态
      （444 题回放里有 10 条）。
    """
    prev = None
    while prev != t:
        prev = t
        t = _RE_PUNCT.sub("", t)
        t = _RE_TAIL.sub("", t)
    return t.strip()

# 在自然停顿处回退，避免切出半句话。
# ★ 把「。！？」也列为断点：不然 `学科学术委员会的届期是几年？可以连任吗` 会截成
#   「…是几年？」（末尾吊一个问号），从问号**前**断开才是干净的话题短语。
_BREAK_CHARS = "，,、；;：:。.！!？? 的和与及"


def _clip(t: str, n: int = TITLE_MAX) -> str:
    """截到 n 字：**优先在自然停顿处回退**，退不了才硬切。

    为什么不能直接 `t[:n]`：实测切出来是「…CET4要考到多少分才能」这种半句
    —— 标题读起来像被截断的句子，而不是一个话题。
    """
    if len(t) <= n:
        return _strip_ends(t)
    # ★ 回退**最多 3 字**，不是能退多远退多远 —— 退太远会切掉半个短语。
    #   实测反例：`进站做博士后对年龄和获博士学位年限有什么要求`，若一路退到
    #   「和」会得到 9 字的「进站做博士后对年龄」——比硬切的 14 字丢的信息更多。
    #   而 `师资博士后和项目博士后的在站工作期限一样吗` 退 3 字到「师资博士后和项目
    #   博士后」，正是一个完整的话题短语，这种就该收。
    for i in range(n, max(n - 4, 3), -1):
        if t[i - 1] in _BREAK_CHARS:
            return _strip_ends(t[: i - 1])
    return _strip_ends(t[:n])


def tidy(text: str) -> str:
    """规则清洗：去开场白 → 去口语修饰 → 去句末语气词与标点。**不截断**。"""
    t = (text or "").strip().replace("\n", " ")
    t = _RE_LEAD.sub("", t)
    t = _RE_SCHOOL.sub("", t)
    t = _RE_WRAP.sub("", t)
    t = _strip_ends(t)
    return re.sub(r"^[，,、。.；;：:\s]+", "", t).strip()


def placeholder_title(question: str) -> str:
    """建会话时的**占位标题**：清洗后按自然停顿截到 `TITLE_MAX`。

    命名叫"占位"是因为它只是个**立即可用**的兜底 —— 首答结束后若模型给出的标题
    更好，会被覆盖（见 `clean_model_title` 与 `routers/chat.py` 的 `_auto_title`）。
    空输入返回空串，由调用方决定默认值。
    """
    t = tidy(question)
    if not t:
        return _clip(question.strip()) if (question or "").strip() else ""
    return _clip(t)


def needs_model(question: str) -> bool:
    """这道题值不值得为它多调一次模型。

    判据：清洗后**超过 TITLE_MAX**（占位标题已被迫截断，说明丢了信息），
    或者原问题本身就长（> `LONG_QUESTION`，多半含铺垫）。

    清洗完就很短的题**直接跳过** —— 实测题面 p50 才 20 字，这类题占位标题本来就够好
    （「专升本学制几年」），为它多调一次模型不划算。
    """
    q = (question or "").strip()
    return len(tidy(q)) > TITLE_MAX or len(q) > LONG_QUESTION


def clean_model_title(raw: str) -> str:
    """把模型输出洗成可用标题；**洗不成则返回空串**（调用方保留占位标题）。

    模型**不可信地遵守格式**（实测约一半超过 12 字、且会漏出「哈～」这类答题语气），
    所以这里不假设它听话：取首行 → 去外壳 → 去语气词标点 → 截断 → 太短就丢弃。
    """
    t = (raw or "").strip()
    t = t.split("\n")[0]                       # 只要第一行（模型偶尔会补充说明）
    if _RE_SRCLEAK.search(t):
        t = _RE_SRCLEAK.split(t)[0]
    t = _RE_WRAP.sub("", t)
    t = _strip_ends(t)
    t = re.sub(r"^[，,、。.；;：:\s]+", "", t).strip()
    if len(t) < 2:                             # 洗没了 / 残成一个字 → 不可用
        return ""
    return _clip(t)